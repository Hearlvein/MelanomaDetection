def get_feature_spec(version: str = DEFAULT_FEATURE_VERSION) -> dict[str, Any]:
    """Return the specification for a user-facing feature version."""
    try:
        return FEATURE_SPECS[version]
    except KeyError as error:
        raise ValueError(
            f"unknown feature version {version!r}; choose from {sorted(FEATURE_SPECS)}"
        ) from error


def get_feature_columns(version: str = DEFAULT_FEATURE_VERSION) -> tuple[str, ...]:
    """Return the model-input columns for a feature version."""
    return tuple(get_feature_spec(version)["all_features"])


def get_numeric_features(version: str = DEFAULT_FEATURE_VERSION) -> tuple[str, ...]:
    return tuple(get_feature_spec(version)["numeric_features"])


def get_categorical_features(version: str = DEFAULT_FEATURE_VERSION) -> tuple[str, ...]:
    return tuple(get_feature_spec(version)["categorical_features"])


def interim_dataset_path(version: str = DEFAULT_FEATURE_VERSION) -> Path:
    return INTERIM_DIR / get_feature_spec(version)["interim_name"]


def split_assignment_path(
    target: str | None = None, version: str = DEFAULT_FEATURE_VERSION
) -> Path:
    target = target or TARGET_DEFINITION
    suffix = get_feature_spec(version)["artifact_suffix"]
    return PROCESSED_DIR / f"split_assignments_{target}{suffix}.csv"


