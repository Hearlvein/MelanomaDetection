def _features_for_spec(spec: dict[str, Any]) -> tuple[tuple[str, ...], tuple[str, ...]]:
    if spec["kind"] != "fitted":
        return (), ()
    numeric = tuple(spec["numeric_features"])
    categorical = tuple(spec["categorical_features"])
    return numeric, categorical


def _build_model_pipeline(spec: dict[str, Any], *, k: int | str | None):
    numeric, categorical = _features_for_spec(spec)
    classifier = LogisticRegression(
        max_iter=5_000,
        class_weight="balanced",
        random_state=config.SEED,
    )
    # Feature-subset baselines keep all of their (small) feature set. The
    # all-feature reference uses the Phase 2 selector.
    model_k = k if spec["name"] == REFERENCE_MODEL else None
    return build_pipeline(
        classifier,
        scale_numeric=True,
        k=model_k,
        numeric_features=numeric,
        categorical_features=categorical,
    )


def _split_counts(frame: pd.DataFrame) -> dict[str, dict[str, Any]]:
    counts: dict[str, dict[str, Any]] = {}
    for split in ("train", "validation", "test"):
        subset = frame.loc[frame["split"] == split]
        positive = int(subset["target"].sum())
        counts[split] = {
            "rows": int(len(subset)),
            "lesions": int(subset["lesion_id"].nunique()),
            "positive": positive,
            "negative": int(len(subset) - positive),
            "prevalence": float(positive / len(subset)) if len(subset) else float("nan"),
        }
    return counts


def _assert_split_isolation(frame: pd.DataFrame) -> None:
    lesion_sets = {
        split: set(frame.loc[frame["split"] == split, "lesion_id"]) for split in ("train", "validation", "test")
    }
    for left, right in (("train", "validation"), ("train", "test"), ("validation", "test")):
        shared = lesion_sets[left] & lesion_sets[right]
        if shared:
            raise RuntimeError(
                f"{len(shared)} lesions overlap between {left} and {right}; "
                "rerun the Phase 1 split before evaluating."
            )


def _evaluate_model(
    spec: dict[str, Any],
    *,
    train: pd.DataFrame,
    validation: pd.DataFrame,
    k: int | str | None,
    cv,
    bootstrap_reps: int,
    min_sensitivity: float,
) -> tuple[dict[str, Any], Any, np.ndarray]:
    feature_columns = list(config.ALL_FEATURES)
    X_train = train[feature_columns]
    y_train = train["target"].to_numpy()
    groups_train = train[config.GROUP_COLUMN].to_numpy()
    X_validation = validation[feature_columns]
    y_validation = validation["target"].to_numpy()

    pipeline = None
    kind = spec["kind"]

    if kind == "constant":
        oof_scores = np.full(len(train), float(spec["score"]), dtype=float)
        validation_scores = np.full(len(validation), float(spec["score"]), dtype=float)
        threshold_f2 = 0.5
        threshold_sensitivity = None
    elif kind == "random":
        rng = np.random.default_rng(config.SEED)
        oof_scores = rng.random(len(train))
        validation_scores = rng.random(len(validation))
        threshold_f2 = 0.5
        threshold_sensitivity = None
    else:
        pipeline = _build_model_pipeline(spec, k=k)
        oof_scores = _positive_scores(
            cross_val_predict(
                pipeline,
                X_train,
                y_train,
                groups=groups_train,
                cv=cv,
                method="predict_proba",
                n_jobs=1,
            )
        )
        threshold_f2 = select_f2_threshold(y_train, oof_scores)
        threshold_sensitivity = select_sensitivity_threshold(
            y_train, oof_scores, min_sensitivity=min_sensitivity
        )
        pipeline.fit(X_train, y_train)
        validation_scores = _positive_scores(pipeline.predict_proba(X_validation))

    metrics = binary_metrics(y_validation, validation_scores, threshold=threshold_f2)
    confidence_intervals = cluster_bootstrap_metric_cis(
        y_validation,
        validation_scores,
        validation[config.GROUP_COLUMN].to_numpy(),
        threshold=threshold_f2,
        n_boot=bootstrap_reps,
        seed=config.SEED,
    )

    high_sensitivity_metrics = None
    if threshold_sensitivity is not None:
        high_sensitivity_metrics = binary_metrics(
            y_validation, validation_scores, threshold=threshold_sensitivity
        )

    numeric, categorical = _features_for_spec(spec)
    result = {
        "name": spec["name"],
        "description": spec["description"],
        "kind": kind,
        "features": {
            "numeric": list(numeric),
            "categorical": list(categorical),
            "numeric_count": len(numeric),
            "categorical_count": len(categorical),
        },
        "threshold_selection": {
            "source": "grouped CV out-of-fold predictions on split == train",
            "objective": "maximise F2",
            "f2_threshold": float(threshold_f2),
            "sensitivity_target": float(min_sensitivity),
            "sensitivity_threshold": (
                float(threshold_sensitivity) if threshold_sensitivity is not None else None
            ),
        },
        "validation": {
            "metrics": metrics,
            "confidence_intervals": confidence_intervals,
            "confusion_matrix": metrics["confusion_matrix"],
        },
        "validation_at_sensitivity_threshold": (
            high_sensitivity_metrics if high_sensitivity_metrics is not None else None
        ),
    }
    return result, pipeline, validation_scores


def _write_figures(
    *,
    target: str,
    y_true: np.ndarray,
    y_score: np.ndarray,
    threshold: float,
    output_dir: Path,
) -> list[str]:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from sklearn.calibration import calibration_curve
        from sklearn.metrics import precision_recall_curve, roc_curve
    except ImportError:
        print("matplotlib is not installed; skipping figures.")
        return []

    output_dir.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    prevalence = float(np.mean(y_true))

    # Precision-recall curve.
    precision, recall, _ = precision_recall_curve(y_true, y_score)
    ap = float(binary_metrics(y_true, y_score, threshold)["average_precision"])
    fig, ax = plt.subplots(figsize=(6, 5))
    ax.plot(recall, precision, label=f"AP = {ap:.3f}")
    ax.axhline(prevalence, color="grey", linestyle="--", label=f"Prevalence = {prevalence:.3f}")
    ax.set_xlabel("Recall / sensitivity")
    ax.set_ylabel("Precision / PPV")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.02)
    ax.set_title(f"Phase 3 precision-recall curve ({target})")
    ax.legend(loc="best")
    fig.tight_layout()
    path = output_dir / f"phase3_{target}_precision_recall.png"
    fig.savefig(path, dpi=150)
    plt.close(fig)
    written.append(_relative(path))

    # ROC curve.
    fpr, tpr, _ = roc_curve(y_true, y_score)
    roc_auc = float(binary_metrics(y_true, y_score, threshold)["roc_auc"])
    fig, ax = plt.subplots(figsize=(6, 5))
    ax.plot(fpr, tpr, label=f"ROC-AUC = {roc_auc:.3f}")
    ax.plot([0, 1], [0, 1], color="grey", linestyle="--", label="Chance")
    ax.set_xlabel("False-positive rate")
    ax.set_ylabel("True-positive rate / sensitivity")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.02)
    ax.set_title(f"Phase 3 ROC curve ({target})")
    ax.legend(loc="best")
    fig.tight_layout()
    path = output_dir / f"phase3_{target}_roc.png"
    fig.savefig(path, dpi=150)
    plt.close(fig)
    written.append(_relative(path))

    # Calibration curve.
    prob_true, prob_pred = calibration_curve(y_true, y_score, n_bins=10, strategy="quantile")
    fig, ax = plt.subplots(figsize=(6, 5))
    ax.plot(prob_pred, prob_true, marker="o", label="Model")
    ax.plot([0, 1], [0, 1], color="grey", linestyle="--", label="Perfect calibration")
    ax.set_xlabel("Mean predicted probability")
    ax.set_ylabel("Observed positive rate")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.02)
    ax.set_title(f"Phase 3 calibration curve ({target})")
    ax.legend(loc="best")
    fig.tight_layout()
    path = output_dir / f"phase3_{target}_calibration.png"
    fig.savefig(path, dpi=150)
    plt.close(fig)
    written.append(_relative(path))

    # Threshold sweep.
    sweep_precision, sweep_recall, sweep_thresholds = precision_recall_curve(y_true, y_score)
    sweep_precision = sweep_precision[:-1]
    sweep_recall = sweep_recall[:-1]
    denominator = 4 * sweep_precision + sweep_recall
    sweep_f2 = np.divide(
        5 * sweep_precision * sweep_recall,
        denominator,
        out=np.zeros_like(sweep_precision, dtype=float),
        where=denominator > 0,
    )
    fig, ax = plt.subplots(figsize=(6, 5))
    ax.plot(sweep_thresholds, sweep_f2, label="F2")
    ax.axvline(threshold, color="firebrick", linestyle="--", label=f"Frozen threshold = {threshold:.3f}")
    ax.set_xlabel("Decision threshold")
    ax.set_ylabel("F2")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.02)
    ax.set_title(f"Phase 3 threshold sweep ({target})")
    ax.legend(loc="best")
    fig.tight_layout()
    path = output_dir / f"phase3_{target}_threshold_sweep.png"
    fig.savefig(path, dpi=150)
    plt.close(fig)
    written.append(_relative(path))

    # Confusion matrix.
    cm = binary_metrics(y_true, y_score, threshold)["confusion_matrix"]
    matrix = np.asarray([[cm["tn"], cm["fp"]], [cm["fn"], cm["tp"]]])
    fig, ax = plt.subplots(figsize=(5, 4))
    image = ax.imshow(matrix, cmap="Blues")
    fig.colorbar(image, ax=ax, fraction=0.046, pad=0.04)
    ax.set_xticks([0, 1], labels=["Predicted 0", "Predicted 1"])
    ax.set_yticks([0, 1], labels=["Actual 0", "Actual 1"])
    for row in range(2):
        for column in range(2):
            ax.text(column, row, str(matrix[row, column]), ha="center", va="center")
    ax.set_title(f"Phase 3 confusion matrix ({target}, threshold={threshold:.3f})")
    fig.tight_layout()
    path = output_dir / f"phase3_{target}_confusion_matrix.png"
    fig.savefig(path, dpi=150)
    plt.close(fig)
    written.append(_relative(path))

    return written


def _format_value(value: float | int | None) -> str:
    if value is None:
        return "—"
    number = float(value)
    if not np.isfinite(number):
        return "—"
    return f"{number:.3f}"


def _format_with_ci(result: dict[str, Any], metric: str) -> str:
    metrics = result["validation"]["metrics"]
    intervals = result["validation"]["confidence_intervals"]
    value = _format_value(metrics.get(metric))
    interval = intervals.get(metric)
    if interval is None or value == "—":
        return value
    return f"{value} [{interval['lower']:.3f}–{interval['upper']:.3f}]"


def _format_threshold(value: float | None) -> str:
    return "—" if value is None else f"{value:.3f}"


def _markdown_table(headers: list[str], rows: list[list[object]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(str(value) for value in row) + " |")
    return "\n".join(lines)


