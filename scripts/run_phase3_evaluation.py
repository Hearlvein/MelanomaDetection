def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--target",
        choices=BINARY_TARGETS,
        default=config.TARGET_DEFINITION,
        help="Binary target definition. Multiclass evaluation is out of scope for Phase 3.",
    )
    parser.add_argument("--n-splits", type=int, default=config.N_SPLITS)
    parser.add_argument("--k", type=int, default=config.DEFAULT_SELECT_K)
    parser.add_argument("--bootstrap-reps", type=int, default=2_000)
    parser.add_argument("--sensitivity", type=float, default=0.90)
    parser.add_argument("--figures", action=argparse.BooleanOptionalAction, default=True)
    args = parser.parse_args()

    frame = load_modeling_frame(args.target)
    _assert_split_isolation(frame)

    train = frame.loc[frame["split"] == "train"].reset_index(drop=True)
    validation = frame.loc[frame["split"] == "validation"].reset_index(drop=True)
    if train.empty or validation.empty:
        raise RuntimeError("training and validation splits must both contain rows")

    # Explicitly assert that the test split is not part of this protocol.
    test = frame.loc[frame["split"] == "test"]
    if not test.empty:
        print(f"Test rows available but not used: {len(test)} rows / {test['lesion_id'].nunique()} lesions")

    spec = config.TARGET_SPECS[args.target]
    target_info = {
        "definition": args.target,
        "description": spec["description"],
        "positive_classes": list(spec["positive"]),
        "negative_classes": list(spec["negative"]),
        "labels": {1: spec["positive_label"], 0: spec["negative_label"]},
    }

    cv = make_grouped_cv(n_splits=args.n_splits, seed=config.SEED)
    model_results: dict[str, dict[str, Any]] = {}
    reference_scores: np.ndarray | None = None

    for model_spec in _model_specs():
        print(f"Evaluating {model_spec['name']}...")
        result, _, validation_scores = _evaluate_model(
            model_spec,
            train=train,
            validation=validation,
            k=args.k,
            cv=cv,
            bootstrap_reps=args.bootstrap_reps,
            min_sensitivity=args.sensitivity,
        )
        model_results[model_spec["name"]] = result
        if model_spec["name"] == REFERENCE_MODEL:
            reference_scores = validation_scores

    if reference_scores is None:
        raise RuntimeError("reference model was not evaluated")

    data_counts = _split_counts(frame)
    created_at = datetime.now(timezone.utc).isoformat()
    protocol = {
        "created_at": created_at,
        "seed": config.SEED,
        "n_splits": args.n_splits,
        "k": args.k,
        "bootstrap_reps": args.bootstrap_reps,
        "sensitivity_target": args.sensitivity,
        "threshold_source": "grouped CV OOF predictions on split == train",
        "test_used": False,
        "reference_model": REFERENCE_MODEL,
    }

    figures: list[str] = []
    if args.figures:
        figures = _write_figures(
            target=args.target,
            y_true=validation["target"].to_numpy(),
            y_score=reference_scores,
            threshold=float(
                model_results[REFERENCE_MODEL]["threshold_selection"]["f2_threshold"]
            ),
            output_dir=config.REPORTS_DIR / "figures",
        )

    metrics_path = config.METRICS_DIR / f"phase3_metrics_{args.target}.json"
    summary_path = config.METRICS_DIR / f"phase3_summary_{args.target}.md"
    config.METRICS_DIR.mkdir(parents=True, exist_ok=True)

    payload = {
        "phase": 3,
        "target": target_info,
        "protocol": protocol,
        "data": data_counts,
        "models": model_results,
        "figures": figures,
        "software": {
            "python": sys.version.split()[0],
            "pandas": pd.__version__,
            "numpy": np.__version__,
            "scikit-learn": sklearn.__version__,
        },
    }

    command = (
        "uv run --python 3.13 "
        "--with pandas --with openpyxl --with scikit-learn==1.9.1 --with matplotlib "
        f"python scripts/run_phase3_evaluation.py --target {args.target} "
        f"--n-splits {args.n_splits} --k {args.k} "
        f"--bootstrap-reps {args.bootstrap_reps} --sensitivity {args.sensitivity}"
    )
    summary = _render_summary(
        target_info=target_info,
        protocol=protocol,
        data_counts=data_counts,
        model_results=model_results,
        figures=figures,
        command=command,
    )

    metrics_path.write_text(
        json.dumps(_sanitise_json(payload), indent=2, default=_json_default) + "\n",
        encoding="utf-8",
    )
    summary_path.write_text(summary, encoding="utf-8")

    reference = model_results[REFERENCE_MODEL]["validation"]["metrics"]
    print()
    print(f"Wrote metrics: {metrics_path}")
    print(f"Wrote summary: {summary_path}")
    print(
        f"Reference {REFERENCE_MODEL}: "
        f"sensitivity={reference['sensitivity']:.3f}, "
        f"specificity={reference['specificity']:.3f}, "
        f"PPV={reference['ppv']:.3f}, "
        f"AP={reference['average_precision']:.3f}, "
        f"ROC-AUC={reference['roc_auc']:.3f}"
    )
    print("Test split was not used.")
    return 0


